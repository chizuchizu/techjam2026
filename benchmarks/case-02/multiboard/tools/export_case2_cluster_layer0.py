#!/usr/bin/env python3
"""Export the official case-2 layer-0 Norm/QKV weights for cluster firmware."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

import numpy as np


D_MODEL = 128
MATRIX_ELEMENTS = D_MODEL * D_MODEL


def read_q12_matrix(blob: bytes, offset: int) -> tuple[np.ndarray, float, int]:
    count, scale = struct.unpack_from("<If", blob, offset)
    offset += 8
    values = np.frombuffer(blob, dtype="<i2", count=count, offset=offset).copy()
    return values, scale, offset + count * 2


def format_array(name: str, c_type: str, values: list[str]) -> str:
    lines = [f"static const {c_type} {name}[{len(values)}] PROGMEM = {{"]
    for begin in range(0, len(values), 12):
        lines.append("    " + ", ".join(values[begin:begin + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def float_literal(value: np.float32) -> str:
    return float(value).hex() + "f"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--baseline", type=Path,
        default=Path("benchmarks/case-02/optimisation/esp32-baseline"),
        help="directory containing weights.bin and weights_q12.bin",
    )
    parser.add_argument(
        "--output", type=Path,
        default=Path(
            "benchmarks/case-02/multiboard/esp32_cluster_transport/"
            "case2_layer0_weights.h"
        ),
    )
    args = parser.parse_args()

    weights = np.fromfile(args.baseline / "weights.bin", dtype="<f4")
    if weights.size != 398_592:
        raise ValueError(f"unexpected fp32 weight count: {weights.size}")

    # Layer-0 flat layout: norm1 gamma/beta, then Q/K/V weight and bias pairs.
    cursor = 0
    norm_weight = weights[cursor:cursor + D_MODEL]
    cursor += D_MODEL
    norm_bias = weights[cursor:cursor + D_MODEL]
    cursor += D_MODEL
    cursor += MATRIX_ELEMENTS
    query_bias = weights[cursor:cursor + D_MODEL]
    cursor += D_MODEL
    cursor += MATRIX_ELEMENTS
    key_bias = weights[cursor:cursor + D_MODEL]
    cursor += D_MODEL
    cursor += MATRIX_ELEMENTS
    value_bias = weights[cursor:cursor + D_MODEL]

    q12_blob = (args.baseline / "weights_q12.bin").read_bytes()
    q_weight, q_scale, q_offset = read_q12_matrix(q12_blob, 0)
    k_weight, k_scale, k_offset = read_q12_matrix(q12_blob, q_offset)
    v_weight, v_scale, _ = read_q12_matrix(q12_blob, k_offset)
    for name, matrix in (("Q", q_weight), ("K", k_weight), ("V", v_weight)):
        if matrix.size != MATRIX_ELEMENTS:
            raise ValueError(f"unexpected {name} matrix size: {matrix.size}")

    sections = [
        "// Generated by benchmarks/case-02/multiboard/tools/"
        "export_case2_cluster_layer0.py. Do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "constexpr uint16_t CASE2_SEQUENCE = 128;",
        "constexpr uint16_t CASE2_MODEL_DIMENSION = 128;",
        "constexpr uint16_t CASE2_HEADS = 4;",
        "constexpr uint16_t CASE2_HEAD_DIMENSION = 32;",
        "constexpr float CASE2_LAYER_NORM_EPSILON = 1.0e-5f;",
        f"constexpr float CASE2_L0_Q_WEIGHT_SCALE = {float_literal(np.float32(q_scale))};",
        f"constexpr float CASE2_L0_K_WEIGHT_SCALE = {float_literal(np.float32(k_scale))};",
        f"constexpr float CASE2_L0_V_WEIGHT_SCALE = {float_literal(np.float32(v_scale))};",
        "",
        format_array("CASE2_L0_NORM_WEIGHT", "float",
                     [float_literal(value) for value in norm_weight]),
        "",
        format_array("CASE2_L0_NORM_BIAS", "float",
                     [float_literal(value) for value in norm_bias]),
        "",
        format_array("CASE2_L0_Q_BIAS", "float",
                     [float_literal(value) for value in query_bias]),
        "",
        format_array("CASE2_L0_K_BIAS", "float",
                     [float_literal(value) for value in key_bias]),
        "",
        format_array("CASE2_L0_V_BIAS", "float",
                     [float_literal(value) for value in value_bias]),
        "",
        format_array("CASE2_L0_Q_WEIGHT", "int16_t",
                     [str(int(value)) for value in q_weight]),
        "",
        format_array("CASE2_L0_K_WEIGHT", "int16_t",
                     [str(int(value)) for value in k_weight]),
        "",
        format_array("CASE2_L0_V_WEIGHT", "int16_t",
                     [str(int(value)) for value in v_weight]),
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(sections))
    print(f"wrote {args.output} ({args.output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
